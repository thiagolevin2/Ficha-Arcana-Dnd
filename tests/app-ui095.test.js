import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {newCharacter} from '../docs/core.js';

// Exercita a navegação real dos botões no DOM simplificado; não substitui teste visual.
test('0.9.5: interface cria companheiro, oferece poderes da linhagem e conjura sem relógio ou alvo',async()=>{
 const c=newCharacter({name:'Saira',classId:'mago',speciesId:'elfo',variant:'Drow',level:5});
 c.knownSpellsByClass.mago=['39'];
 const storage={arcana2024:JSON.stringify({version:3,characters:[c],activeId:c.id,history:[]}), 'arcana-dice3d':'off'},els={},events={};
 globalThis.localStorage={getItem:k=>storage[k]??null,setItem:(k,v)=>storage[k]=v};
 globalThis.document={documentElement:{dataset:{}},body:{style:{}},activeElement:{isConnected:false},querySelector:key=>els[key]??={innerHTML:'',value:'',checked:false,focus(){},setSelectionRange(){},firstChild:null},querySelectorAll:()=>[],addEventListener:(kind,fn)=>(events[kind]??=[]).push(fn)};
 globalThis.window={scrollTo(){},print(){},confirm:()=>true};globalThis.requestAnimationFrame=()=>{};
 globalThis.fetch=async url=>({ok:true,json:async()=>JSON.parse(await fs.readFile(new URL('../docs/'+url,import.meta.url),'utf8'))});
 await import('../docs/app.js?ui095');
 const click=async(action,data={})=>{const event={target:{closest:()=>({disabled:false,dataset:{action,...data}})},preventDefault(){}};for(const fn of events.click||[])await fn(event);};
 const ch=()=>JSON.parse(storage.arcana2024).characters[0];
 await click('navigate',{view:'resources'});
 assert.match(els['#app'].innerHTML,/Linhagem \/ herança/);
 assert.match(els['#app'].innerHTML,/Atacante Selvagem/); // Talento de origem
 assert.doesNotMatch(els['#app'].innerHTML,/data-tab="transforms"/);
 await click('095-action-edit',{id:'lineage:elfo:Drow'});
 assert.match(els['#modal-root'].innerHTML,/Valor fixo ou dados/);
 document.querySelector('#095-action-mode').value='healing';
 document.querySelector('#095-action-formula').value='4';
 document.querySelector('#095-action-max').value='1';
 document.querySelector('#095-action-recovery').value='long';
 document.querySelector('#095-action-resource').value='';
 document.querySelector('#095-action-cost').value='0';
 document.querySelector('#095-action-note').value='Apenas quando uma fonte realmente conceder esta cura.';
 await click('095-action-save',{id:'lineage:elfo:Drow',infusion:'0'});
 assert.equal(ch().abilityActions['lineage:elfo:Drow'].formula,'4');
 await click('095-action-use',{id:'lineage:elfo:Drow'});
 assert.equal(ch().abilityActions['lineage:elfo:Drow'].used,1);
 await click('navigate',{view:'companions'});
 await click('093-companion-dialog');
 assert.match(els['#modal-root'].innerHTML,/095-companion-name/);
 assert.match(els['#modal-root'].innerHTML,/095-companion-damage/);
 const data={name:'Coruja de Saira',kind:'familiar',source:'Invocar Familiar',ac:'12',hpmax:'3',hp:'3',speed:'9',attack:'Garras',bonus:'2',damage:'1d4',notes:'Acompanha a jornada'};
 for(const [k,v] of Object.entries(data))document.querySelector('#095-companion-'+k).value=v;
 await click('095-companion-save',{id:'new'});
 assert.equal(ch().companions[0].name,'Coruja de Saira');
 await click('navigate',{view:'spells'});
 assert.match(els['#app'].innerHTML,/Bolha Ácida/);
 await click('cast-dialog',{id:'39'});
 assert.match(els['#modal-root'].innerHTML,/Somente registrar uso/);
 document.querySelector('#cast-source').value='class:mago';
 document.querySelector('#095-spell-mode').value='none';
 document.querySelector('#095-spell-formula').value='';
 document.querySelector('#095-spell-ability').value='int';
 await click('cast-confirm',{id:'39'});
 assert.equal(ch().spellRolls['39'].mode,'none');
 assert.equal(ch().sceneEffects.length,0);
 assert.equal(ch().companions[0].name,'Coruja de Saira');
});
